/**
 * Build OMP's <omp-tool-view> web-component bundle for the desktop app.
 *
 * Up to OMP 18.13 the npm package shipped this bundle prebuilt
 * (`src/export/html/tool-views.generated.js`) and a sync script copied it on
 * every build. OMP 18.14 moved its HTML export to a hosted viewer and stopped
 * publishing the standalone bundle, so it is now built here from OMP's own
 * source — the same entry point and the same recipe upstream used
 * (`packages/collab-web/src/tool-render/standalone.tsx`: one IIFE, React
 * included, CSS inlined).
 *
 * The output is checked in. Run this on every OMP bump:
 *
 *   git clone --depth 1 --branch v<PIN> https://github.com/can1357/oh-my-pi <dir>
 *   bun scripts/build-tool-views.ts <dir>
 *
 * `omp-pin.test.ts` fails when the committed bundle was built from a
 * different OMP version than the pin, so a bump cannot ship stale tool cards.
 */

import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const dst = join(root, "apps/desktop/src/vendor/tool-views.generated.js");

function fail(message: string): never {
  console.error(message);
  process.exit(1);
}

function readJson(path: string): Record<string, any> {
  return JSON.parse(readFileSync(path, "utf8"));
}

const checkoutArg = process.argv[2];
if (!checkoutArg) {
  fail("usage: bun scripts/build-tool-views.ts <path to an oh-my-pi checkout at the pinned tag>");
}
const checkout = resolve(checkoutArg);
const collabSrc = join(checkout, "packages/collab-web/src");
const entry = "src/tool-render/standalone.tsx";
if (!existsSync(join(collabSrc, "tool-render/standalone.tsx"))) {
  fail(`${checkout} is not an oh-my-pi checkout: packages/collab-web/${entry} is missing`);
}

// The checkout must be the pinned OMP: the renderers read each tool's
// args/details shapes, which is exactly what changes between versions.
const pin = String(
  readJson(join(root, "packages/engine/package.json")).dependencies["@oh-my-pi/pi-coding-agent"],
);
const checkoutVersion = String(readJson(join(checkout, "packages/utils/package.json")).version);
if (checkoutVersion !== pin) {
  fail(`the checkout is OMP ${checkoutVersion}, but this repo pins ${pin}`);
}

// Third-party versions come from upstream's own catalog, so the bundle is
// built against what upstream tested the renderers with.
const catalog: Record<string, string> = readJson(join(checkout, "package.json")).workspaces
  ?.catalog;
const dependencies: Record<string, string> = {
  "@oh-my-pi/pi-utils": pin,
  "@oh-my-pi/pi-wire": pin,
};
for (const name of ["react", "react-dom", "katex"]) {
  const version = catalog?.[name];
  if (!version) fail(`upstream's catalog no longer lists ${name}; update this script`);
  dependencies[name] = version;
}

// Build from a copy: nothing is installed into, or run from, the checkout.
const work = mkdtempSync(join(tmpdir(), "omp-tool-views-"));
try {
  cpSync(collabSrc, join(work, "src"), { recursive: true });
  await Bun.write(
    join(work, "package.json"),
    JSON.stringify({ name: "omp-tool-views-build", private: true, dependencies }, null, 2),
  );
  const install = Bun.spawnSync([process.execPath, "install", "--no-save"], {
    cwd: work,
    stdout: "inherit",
    stderr: "inherit",
  });
  if (install.exitCode !== 0) fail("installing the bundle's dependencies failed");

  const result = await Bun.build({
    entrypoints: [join(work, entry)],
    target: "browser",
    format: "iife",
    minify: true,
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
  });
  if (!result.success) {
    for (const log of result.logs) console.error(String(log));
    fail("bundling the tool views failed");
  }

  let js = "";
  let css = "";
  for (const artifact of result.outputs) {
    if (artifact.path.endsWith(".css")) css += await artifact.text();
    else if (artifact.path.endsWith(".js")) js += await artifact.text();
    else fail(`unexpected bundle output: ${artifact.path}`);
  }
  if (!js) fail("the bundle produced no JavaScript");
  if (!js.includes("omp-tool-view")) fail("the bundle does not register <omp-tool-view>");

  const styleInject = css
    ? `(()=>{var s=document.createElement("style");s.dataset.ompToolViews="";s.textContent=${JSON.stringify(css.trim())};(document.head||document.documentElement).appendChild(s);})();\n`
    : "";
  const banner = `// Auto-generated by scripts/build-tool-views.ts from OMP v${pin} (packages/collab-web/${entry}) - DO NOT EDIT\n`;
  mkdirSync(dirname(dst), { recursive: true });
  await Bun.write(dst, banner + styleInject + js);
  const kib = ((banner.length + styleInject.length + js.length) / 1024).toFixed(1);
  console.log(`built omp-tool-view bundle from OMP v${pin} -> ${dst} (${kib} KiB)`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
